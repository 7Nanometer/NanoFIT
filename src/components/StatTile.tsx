// ============================================================
// 一个读数格
// ============================================================
// 统计页里那些"一个大数字 + 一句说明"的格子。
//
// 【它自己不画边框，也不定宽】
// 边框、分格线、宽度全都交给外面那个 .stat-grid 管。
// 这样同一组数字是一个整体（一块面板上的四个读数），
// 而不是四张各管各的小卡片 —— 后者看着像四个不相干的小部件。
//
// tabular-nums 的作用：让每个数字占的宽度一样。
// 不写的话，数字变化时整块会左右抖动一下。
// ============================================================

type Props = {
  label: string // 小字：这个数字是什么
  value: string // 大字：数字本身（已经格式化好的文字）
  hint?: string // 更小的字：补充说明
}

export function StatTile({ label, value, hint }: Props) {
  return (
    <div>
      {/* 标签用 .t-label（12px、淡色、字距拉开）——
          它和下面那个数字必须拉得足够开，否则"这一格是什么"会
          和"这一格是多少"读成一样重的东西 */}
      <div className="t-label truncate">{label}</div>
      {/* 【数字为什么是 21px 加粗，而不是更大】
          它得比标签和说明都重得多 —— 这一页存在的意义就是这几个数，
          一屏扫下去应该先看到数字本身，说明文字退到背景里。
          但**不能再大了**：时长那两格写的是"1 小时 32 分"，
          八个字符宽。28px 时它要 152 像素，而手机上每格只有 146 像素 ——
          会折成"1 小时 32 / 分"两行，把整块面板的高度撑得参差不齐
          （实测过：第一版就是 28px，截图里第三格明显比第四格高）。
          21px 下它占 114 像素，最窄的 320px 机器上也放得下。 */}
      <div className="t-num mt-1 text-xl font-bold text-ink">{value}</div>
      {hint !== undefined && hint !== '' && (
        <div className="mt-0.5 text-xs text-muted">{hint}</div>
      )}
    </div>
  )
}
